#!/bin/bash
# core-pin.sh <version> — pin a shared-core release (C5, #251, ADR 0025).
#
# Downloads release.json and the Swift bindings of the GitHub release
# core-v<version> and writes core/release/: the pinned manifest and a local
# Swift package whose binaryTarget points at the release's XCFramework zip by
# URL and checksum. Xcode then fetches the prebuilt core; no app build
# compiles Rust, and no machine needs a Rust toolchain.
#
# Usage: scripts/core-pin.sh 0.1.0
set -euo pipefail

version="${1:?usage: core-pin.sh <version>}"
tag="core-v$version"
root="$(cd "$(dirname "$0")/.." && pwd)"
release="$root/core/release"
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

wasm_name="septena-core-wasm-web-$version.tgz"
kotlin_name="septena-core-kotlin-$version.zip"
gh release download "$tag" --repo michellzappa/septena --dir "$tmp" \
  --pattern release.json --pattern "SeptenaSharedCore-$version.swift" --pattern "$wasm_name" \
  --pattern "$kotlin_name"

zip_name="SeptenaSharedCoreFFI-$version.xcframework.zip"
url="$(jq -r --arg n "$zip_name" '.assets[] | select(.name == $n) | .url' "$tmp/release.json")"
sum="$(jq -r --arg n "$zip_name" '.assets[] | select(.name == $n) | .sha256' "$tmp/release.json")"
[ -n "$url" ] && [ "$url" != null ] || { echo "core-pin: $zip_name is not in $tag" >&2; exit 1; }

mkdir -p "$release/swift/Sources/SeptenaSharedCore"
cp "$tmp/release.json" "$release/release.json"
cp "$tmp/SeptenaSharedCore-$version.swift" "$release/swift/Sources/SeptenaSharedCore/SeptenaSharedCore.swift"

cat > "$release/swift/Package.swift" <<EOF
// swift-tools-version: 6.0
// GENERATED by scripts/core-pin.sh $version — do not edit by hand.
// The shared Rust core (ADR 0025), pinned to the GitHub release $tag.
import PackageDescription

let package = Package(
    name: "SeptenaSharedCore",
    platforms: [.iOS(.v17), .macOS(.v14)],
    products: [
        .library(name: "SeptenaSharedCore", targets: ["SeptenaSharedCore"]),
    ],
    targets: [
        .binaryTarget(
            name: "SeptenaSharedCoreFFI",
            url: "$url",
            checksum: "$sum"
        ),
        .target(
            name: "SeptenaSharedCore",
            dependencies: ["SeptenaSharedCoreFFI"],
            swiftSettings: [.swiftLanguageMode(.v5)]
        ),
    ]
)
EOF

# The Worker (backend/) runs the same release as WASM (C3, #249). The files
# are committed, so a self-hosted deploy stays a plain `wrangler deploy`.
wasm_sum="$(jq -r --arg n "$wasm_name" '.assets[] | select(.name == $n) | .sha256' "$tmp/release.json")"
got_sum="$(shasum -a 256 "$tmp/$wasm_name" | cut -d' ' -f1)"
[ "$wasm_sum" = "$got_sum" ] || { echo "core-pin: $wasm_name checksum mismatch" >&2; exit 1; }
wasm_dir="$root/backend/src/core/wasm"
rm -rf "$wasm_dir"
mkdir -p "$wasm_dir"
tar -xzf "$tmp/$wasm_name" -C "$wasm_dir"
printf '%s\n' "$version" > "$wasm_dir/VERSION"

# Android and the JVM (C1, #247): the UniFFI Kotlin bindings are source and
# are committed; the native libraries come from release.json at build time
# (android/app/build.gradle.kts, task fetchCoreJniLibs).
kotlin_sum="$(jq -r --arg n "$kotlin_name" '.assets[] | select(.name == $n) | .sha256' "$tmp/release.json")"
got_sum="$(shasum -a 256 "$tmp/$kotlin_name" | cut -d' ' -f1)"
[ "$kotlin_sum" = "$got_sum" ] || { echo "core-pin: $kotlin_name checksum mismatch" >&2; exit 1; }
mkdir -p "$tmp/kotlin"
unzip -q -o "$tmp/$kotlin_name" -d "$tmp/kotlin"
kotlin_dir="$root/android/core/src/main/kotlin/app/septena/sharedcore"
mkdir -p "$kotlin_dir"
cp "$tmp/kotlin/app/septena/sharedcore/septena_core.kt" "$kotlin_dir/septena_core.kt"

echo "pinned $tag in core/release/ (XCFramework $sum), backend/src/core/wasm/ and android/core (Kotlin bindings)"
