import {
  AlignLeft,
  ArrowUpDown,
  Bell,
  Bot,
  Calendar,
  Check,
  Circle,
  CircleCheck,
  CircleDashed,
  CircleEllipsis,
  CircleStop,
  Clock,
  Eye,
  Hourglass,
  History,
  Infinity as InfinityIcon,
  Flag,
  Folder,
  Inbox,
  Layers,
  ListChecks,
  Mail,
  MessageCircleQuestion,
  MessageSquare,
  MessageSquareText,
  MessagesSquare,
  MonitorSmartphone,
  Paperclip,
  Plus,
  Repeat,
  Star,
  Sun,
  Trash2,
  type LucideIcon,
  type LucideProps,
} from "lucide-react";
import { ICONS } from "@/lib/generated/registries";

// The lucide icons that registry/icons.json names for smart lists, their groups,
// sign-in methods, and task row chrome. Named imports keep the rest of lucide out of the bundle.
const LUCIDE: Record<string, LucideIcon> = {
  "align-left": AlignLeft,
  "arrow-up-down": ArrowUpDown,
  bell: Bell,
  bot: Bot,
  calendar: Calendar,
  check: Check,
  "circle-check": CircleCheck,
  "circle-dashed": CircleDashed,
  "circle-ellipsis": CircleEllipsis,
  "circle-stop": CircleStop,
  clock: Clock,
  eye: Eye,
  hourglass: Hourglass,
  history: History,
  infinity: InfinityIcon,
  flag: Flag,
  folder: Folder,
  inbox: Inbox,
  layers: Layers,
  "list-checks": ListChecks,
  mail: Mail,
  "message-circle-question": MessageCircleQuestion,
  "message-square": MessageSquare,
  "message-square-text": MessageSquareText,
  "messages-square": MessagesSquare,
  "monitor-smartphone": MonitorSmartphone,
  paperclip: Paperclip,
  plus: Plus,
  repeat: Repeat,
  star: Star,
  sun: Sun,
  "trash-2": Trash2,
};

const REGISTRY_ICONS: Record<string, { lucide: string } | undefined> = ICONS;

/** The icon of a registry/icons.json token, such as `list.review` or `task.added_by_agent`. */
export function RegistryIcon({ token, ...props }: { token: string } & LucideProps) {
  const Icon = LUCIDE[REGISTRY_ICONS[token]?.lucide ?? ""] ?? Circle;
  return <Icon {...props} />;
}
